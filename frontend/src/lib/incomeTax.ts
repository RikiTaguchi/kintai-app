/**
 * 勤務年月（year, month）から新版・旧版どちらの税額表を使うかを判定する。
 *
 * 支払日ルール: 翌月10日払い
 * - 旧版: 2025年11月分まで（支払日 2025/12/10 まで）
 * - 新版: 2025年12月分から（支払日 2026/1/10 以降）
 */
const NEW_TABLE_START_YEAR = 2025;
const NEW_TABLE_START_MONTH = 12;

/**
 * 月間支給額から源泉徴収所得税を計算する。
 *
 * @param grossPay 月間支給総額
 * @param year 勤務年（省略時は新版テーブルを使用）
 * @param month 勤務月（省略時は新版テーブルを使用）
 */
export function calcIncomeTax(grossPay: number, year?: number, month?: number): number {
  const useNewTable =
    year === undefined ||
    month === undefined ||
    year > NEW_TABLE_START_YEAR ||
    (year === NEW_TABLE_START_YEAR && month >= NEW_TABLE_START_MONTH);

  const table = useNewTable ? TAX_TABLE_NEW : TAX_TABLE_OLD;
  const bracket = table.find((b) => grossPay >= b.min && grossPay < b.max);
  return bracket?.tax ?? 0;
}
